    var writer: std.Io.Writer = .fixed(&buffer);
    try writeJarLine(&writer, line);
    try testing.expectEqualStrings(text, writer.buffered());
}

test "a domain cookie and a HttpOnly cookie write the prefixes curl writes" {
    var buffer: [256]u8 = undefined;
    var writer: std.Io.Writer = .fixed(&buffer);
    try writeJarLine(&writer, .{
        .domain = "example.test",
        .include_subdomains = true,
        .path = "/",
        .secure = true,
        .expires = 2000000000,
        .name = "n",
        .value = "v",
        .http_only = true,
    });
    try testing.expectEqualStrings(
        "#HttpOnly_.example.test\tTRUE\t/\tTRUE\t2000000000\tn\tv\n",
        writer.buffered(),
    );
}

test "a CR, an LF, a NUL, or a semicolon in a cookie value is refused" {
    try testing.expect(wireSafe("abc123"));
    try testing.expect(!wireSafe("a\r\nX-Injected: yes"));
    try testing.expect(!wireSafe("a\nb"));
    try testing.expect(!wireSafe("a\x00b"));
    try testing.expect(!wireSafe("a;b=c"));
    try testing.expect(!wireSafe("a\tb"));
}

test "a tab in a domain or a path is refused, so a jar line keeps its columns" {
    try testing.expect(fieldSafe("/dir/page"));
    try testing.expect(!fieldSafe("/dir\tFALSE\t/"));
    try testing.expect(!fieldSafe("a\nb"));
}

test "the three cookie date formats all read to the same instant" {
    const want: i64 = 1623233894; // 2021-06-09 10:18:14 UTC
    try testing.expectEqual(@as(?i64, want), parseDate("Wed, 09 Jun 2021 10:18:14 GMT"));
    try testing.expectEqual(@as(?i64, want), parseDate("Wednesday, 09-Jun-21 10:18:14 GMT"));
    try testing.expectEqual(@as(?i64, want), parseDate("Wed Jun  9 10:18:14 2021"));
}

test "the epoch itself and a leap day read exactly" {
    try testing.expectEqual(@as(?i64, 0), parseDate("Thu, 01 Jan 1970 00:00:00 GMT"));
    // 2000-02-29 is a leap day of a century that is a leap year.
    try testing.expectEqual(@as(?i64, 951782400), parseDate("Tue, 29 Feb 2000 00:00:00 GMT"));
}

test "a date this build cannot read is null, which leaves a session cookie" {
    try testing.expectEqual(@as(?i64, null), parseDate(""));
    try testing.expectEqual(@as(?i64, null), parseDate("not a date at all"));
    try testing.expectEqual(@as(?i64, null), parseDate("Wed, 09 Jun 2021 GMT"));
    try testing.expectEqual(@as(?i64, null), parseDate("Wed, 99 Jun 2021 10:18:14 GMT"));
    try testing.expectEqual(@as(?i64, null), parseDate("Wed, 09 Jun 2021 99:18:14 GMT"));
    var long: [200]u8 = undefined;
    @memset(&long, 'x');
    try testing.expectEqual(@as(?i64, null), parseDate(&long));
}

test "a two-digit year splits at 69, the way RFC 6265 says" {
    const y2069 = parseDate("Wed, 01 Jan 69 00:00:00 GMT").?;
    const y1970 = parseDate("Wed, 01 Jan 70 00:00:00 GMT").?;
    try testing.expectEqual(@as(i64, 0), y1970);
    try testing.expect(y2069 > y1970);
}
